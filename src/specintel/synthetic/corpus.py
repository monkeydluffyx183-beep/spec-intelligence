@dataclass
class BuiltCorpus:
    root: Path
    documents: list[dict[str, Any]] = field(default_factory=list)
    manifest: list[dict[str, Any]] = field(default_factory=list)
    gold: list[dict[str, Any]] = field(default_factory=list)

    def page_of(self, anchor: str) -> int | None:
        for entry in self.manifest:
            if entry.get("anchor") == anchor:
                return int(entry["page"])
        return None

    def entry(self, anchor: str) -> dict[str, Any] | None:
        for e in self.manifest:
            if e.get("anchor") == anchor:
                return e
        return None


def build_corpus(out_dir: str | Path, *, gold_path: str | Path | None = None,
                 log: Any = None) -> BuiltCorpus:
    """Write the synthetic corpus (PDFs + manifest + gold set) under ``out_dir``."""
    from specintel.common.logging import log_event
    from specintel.synthetic.gold import build_gold_questions

    root = Path(out_dir)
    root.mkdir(parents=True, exist_ok=True)
    corpus = BuiltCorpus(root=root)

    for spec in DOC_SPECS:
        doc_files: list[str] = []
        for file_name, blocks_fn, running_title in spec.files:
            writer = PdfWriter(title=f"{spec.title} ({spec.revision}) — synthetic stand-in")
            title_page(writer, spec.title, f"Revision {spec.revision}", spec.doc_id, spec.date,
                       LICENSE_LINE, spec.toc)
            flow = Flow(writer, spec.doc_id, spec.revision, running_title,
                        start_page_no=len(writer.pages))
            flow.new_page()
            for block in blocks_fn():
                flow.add(block)
            path = writer.write(root / spec.doc_id / file_name)
            corpus.manifest.extend(flow.manifest)
            doc_files.append(str(path))
            if log:
                log_event(log, "synthetic.doc", doc=spec.doc_id, file=file_name, pages=flow.page_no,
                          elements=len(flow.manifest))
        corpus.documents.append({
            "doc_id": spec.doc_id,
            "title": spec.title,
            "revision": spec.revision,
            "date": spec.date,
            "files": doc_files,
            "pages": sum(1 for m in corpus.manifest if m["doc_id"] == spec.doc_id and m["type"] == "section_heading")
                     and max((int(m["page"]) for m in corpus.manifest if m["doc_id"] == spec.doc_id), default=0),
            "pages_expected_in_real_document": spec.pages_expected,
            "elements": sum(1 for m in corpus.manifest if m["doc_id"] == spec.doc_id),
        })

    manifest_path = root / "manifest.json"
    manifest_path.write_text(json.dumps({"documents": corpus.documents, "elements": corpus.manifest},
                                        indent=1, ensure_ascii=False), encoding="utf-8")
    corpus.gold = build_gold_questions(corpus)
    if gold_path:
        gp = Path(gold_path)
        gp.parent.mkdir(parents=True, exist_ok=True)
        gp.write_text("\n".join(json.dumps(q, ensure_ascii=False) for q in corpus.gold) + "\n", encoding="utf-8")
    if log:
        log_event(log, "synthetic.corpus", documents=len(corpus.documents), elements=len(corpus.manifest),
                  gold_questions=len(corpus.gold), out=str(root))
    return corpus
